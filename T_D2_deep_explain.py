#
# 现在: φ^r + d/(2φ^r) 是什么?
# φ^7 + 56/(2·29.034) = 29.034 + 0.964 = 29.999

lhs = dim + delta - (r-1)*h  # = r + h + Δ = 30
rhs_exact = r + h + delta
print(f"  dim + Δ - (r-1)h = {dim} + {delta} - {(r-1)*h} = {lhs}")
print(f"  = r + h + Δ = {r} + {h} + {delta} = {rhs_exact}")

phi_r_term = phi**7 + d/(2*phi**7)
print(f"\n  φ^r + d/(2φ^r) = {phi**7:.6f} + {d/(2*phi**7):.6f} = {phi_r_term:.6f}")
print(f"  r + h + Δ = {rhs_exact}")
print(f"  差 = {rhs_exact - phi_r_term:.10f}")

# 那这个差是什么?
# 30 - (φ^7 + 28/φ^7) 
# = 30 - φ^7 - 28·φ^{-7}
# 用 φ^7 = L_7/2 + F_7·√5/2 的精确表达... 不，更简单:
# φ^7 = (L_7 + F_7·√5)/2 = (29 + 13√5)/2
