# ================================================================
# 推导 1: α⁻¹ 的恒等式
# ================================================================
print("\n━━━ 推导 1: dim + Δ 与 φ^r 的恒等式 ━━━\n")

# 声明: dim + Δ = (r-1)h + φ^r + d/(2φ^r) + O(φ^{-2r})
# 
# 证明:
# dim = r(h+1) = rh + r
# Δ = 5
# 所以 dim + Δ = rh + r + 5
#
# 另一边:
# (r-1)h = rh - h
# 所以 dim + Δ - (r-1)h = rh + r + 5 - rh + h = r + h + 5
