# |ψ^7| = |ψ|^7 = φ^{-7} = 0.0344...
# 所以 φ^7 ≈ 29 + 0.034 = 29.034

print(f"  φ^7 = L_7 - ψ^7 = {int(round(phi**7+psi**7))} - ({psi**7:.6f}) = {phi**7:.6f}")
print(f"  φ^7 = Z_r + |ψ|^r  (分配函数 + 暗修正)")
