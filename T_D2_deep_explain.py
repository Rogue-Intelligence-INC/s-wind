print(f"    = φ^7/√5 × [[φ,1],[1,1/φ]]")
print(f"    = [[{phi**7*phi/sqrt5:.4f}, {phi**7/sqrt5:.4f}], [{phi**7/sqrt5:.4f}, {phi**7/(phi*sqrt5):.4f}]]")

# 验证
print(f"\n  谱分解验证:")
