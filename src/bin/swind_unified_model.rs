    println!("           S-wind 统一物理模型构建器");
    println!("           基于 P(2) = Q(4) = 137 的精确关系");
    println!("================================================================================\n");

    let p_coeffs: [i128; 5] = [2, -5, 4, 15, 99];
    let q_coeffs: [i128; 5] = [1, -2, 0, 2, 1];

    // ========================================================================
    // 阶段 1: 核心恒等式 P(2) = Q(4) = 137
    // ========================================================================

    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
    println!("阶段 1: 核心恒等式验证");
    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n");

    let p2 = eval_poly(&p_coeffs, 2);
    let q4 = eval_poly(&q_coeffs, 4);

    println!("精确计算:");
    println!("  P(2) = 2×16 - 5×8 + 4×4 + 15×2 + 99");
    println!("       = 32 - 40 + 16 + 30 + 99");
    println!("       = {}", p2);
    println!();
