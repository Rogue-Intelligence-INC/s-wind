        let const_term = q_k;
        let n_coeff = p_k - q_k;
        let power = 4 - k;
        if n_coeff >= 0 {
            println!("  a_{}(n) = {} + {}n", power, const_term, n_coeff);
        } else {
            println!("  a_{}(n) = {} - {}n", power, const_term, -n_coeff);
        }
