fn print_domain(name: &str, counts: (usize, usize, usize), examples: &[(&str, &str)]) {
    println!("#### {}", name);
    println!();
    println!("- Constants: {}, Laws: {}, Theorems: {}", counts.0, counts.1, counts.2);
    println!();
    println!("Key formulas:");
    for (n, f) in examples {
        println!("- **{}**: `{}`", n, f);
    }
    println!();
}
