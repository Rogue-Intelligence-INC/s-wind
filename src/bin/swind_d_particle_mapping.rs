//! S-wind D-粒子映射探索
//!
//! 目标: 寻找 "为什么 D=X 对应粒子 Y" 的模式
//!
//! 探索方向:
//! 1. D 值与粒子性质的代数关系
//! 2. 质量阶梯与 D 的关系
//! 3. 量子数与 D 的关系
//! 4. 跨多项式一致性检验
//!
//! 纯代数计算 (Rational)

use s_wind::Rational;

fn main() {
    println!("================================================================================");
    println!("           S-wind D-粒子映射探索");
    println!("           目标: 寻找 D 与粒子性质的结构性关系");
    println!("================================================================================\n");

    // ========================================================================
    // 阶段 1: 分析五常数多项式的 D-粒子映射
    // ========================================================================

    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
    println!("阶段 1: 五常数多项式 D-粒子映射分析");
    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n");

    // 五常数多项式: P(D) = 2D⁴ - 5D³ + 4D² + 15D + 99
    let five_const_poly = |d: i128| -> i128 {
        2*d.pow(4) - 5*d.pow(3) + 4*d.pow(2) + 15*d + 99
    };

    // 已知映射
    let mappings = [
        (2, 137, "α⁻¹", 0.0, "电磁耦合常数逆"),
        (3, 207, "mμ/me", 206.768, "缪子/电子质量比"),
        (6, 1845, "mp/me", 1836.15, "质子/电子质量比"),
        (6, 1845, "mn/me", 1838.68, "中子/电子质量比"),
        (7, 3487, "mτ/me", 3477.23, "τ子/电子质量比"),
    ];

    println!("映射表:\n");
    println!("  D | P(D) | 物理常数 | 测量值      | 粒子性质");
    println!("  --|------|----------|-------------|------------------");

    for (d, p_d, name, measured, desc) in &mappings {
        let calculated = five_const_poly(*d);
        let error = if *measured > 0.0 {
            (calculated as f64 - measured) / measured * 100.0
        } else {
            0.0
        };
        println!("  {} | {:4} | {:8} | {:11.3} | {} ({:.3}%)", 
                 d, calculated, name, measured, desc, error.abs());
    }

    // ========================================================================
    // 阶段 2: 寻找 D 与粒子性质的代数关系
    // ========================================================================

    println!("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
    println!("阶段 2: D 与粒子性质的代数关系");
    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n");

    // 假设 1: D 与代数数/轻子代数有关
    println!("假设 1: D 与粒子代数有关\n");
    println!("  D=2 → α⁻¹ (电磁, U(1))");
    println!("  D=3 → mμ/me (第二代轻子)");
    println!("  D=6 → mp/me, mn/me (重子, D=3×2)");
    println!("  D=7 → mτ/me (第三代轻子, D=3+4?)");
    println!("\n  观察: D=6 = 2×3 (电磁 × 轻子代?)");
    println!("         D=7 = ? (无明显因子关系)");

    // 假设 2: D 与质量阶梯有关
    println!("\n假设 2: D 与质量阶梯\n");
    
    let mass_ratios: [(&str, f64); 5] = [
        ("me", 1.0),
        ("mμ", 206.768),
        ("mτ", 3477.23),
        ("mp", 1836.15),
        ("mn", 1838.68),
    ];

    // 计算质量比的对数
    println!("  粒子 | 质量/me | log(质量/me) | D 值");
    println!("  -----|---------|--------------|------");
    for (name, ratio) in &mass_ratios {
        let log_ratio = ratio.ln();
        let d_val = match *name {
            "me" => 1,
            "mμ" => 3,
            "mτ" => 7,
            "mp" => 6,
            "mn" => 6,
            _ => 0,
        };
        println!("  {:4} | {:7.2} | {:12.4} | {}", name, ratio, log_ratio, d_val);
    }

    // 检查 D 与 log(mass) 的关系
    println!("\n  测试: D ∝ log(mass)?");
    let mu_d = 3.0;
    let mu_log = 206.768_f64.ln();
    let k = mu_d / mu_log;
    println!("    从 mμ: k = D / log(m/me) = {} / {} ≈ {:.4}", mu_d, mu_log, k);
    
    for (name, ratio) in &mass_ratios {
        let predicted_d = ratio.ln() * k;
        let actual_d = match *name {
            "me" => 1.0,
            "mμ" => 3.0,
            "mτ" => 7.0,
            "mp" => 6.0,
            "mn" => 6.0,
            _ => 0.0,
        };
        println!("    {}: 预测 D = {:.2}, 实际 D = {}", name, predicted_d, actual_d);
    }
    println!("\n  结论: D ∝ log(mass) 关系不成立");

    // ========================================================================
    // 阶段 3: 质子/中子在同一 D 的物理意义
    // ========================================================================

    println!("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
    println!("阶段 3: 质子/中子在 D=6 的分析");
    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n");

    let p6 = five_const_poly(6);
    let mp_me = 1836.15;
    let mn_me = 1838.68;
    let avg_nucleon = (mp_me + mn_me) / 2.0;

    println!("P(6) = {}", p6);
    println!("mp/me = {}", mp_me);
    println!("mn/me = {}", mn_me);
    println!("平均核子质量比 = {:.2}", avg_nucleon);
    println!("P(6) - 平均核子 = {:.2}", p6 as f64 - avg_nucleon);
    println!("\n观察: P(6) = 1845 更接近核子平均值 ({:.2})", avg_nucleon);
    println!("      这可能暗示 D=6 对应 '核子' 而非单独的质子或中子");

    // ========================================================================
    // 阶段 4: 代数结构分析 - D 序列的性质
    // ========================================================================

    println!("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
    println!("阶段 4: D 序列的代数性质");
    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n");

    let d_values = [2, 3, 6, 7];
    
    println!("有物理意义的 D 值: {:?}\n", d_values);
    
    // 分析差分
    let diffs: Vec<i32> = d_values.windows(2).map(|w| w[1] - w[0]).collect();
    println!("差分 ΔD: {:?}", diffs);
    println!("  2 → 3: +1");
    println!("  3 → 6: +3");
    println!("  6 → 7: +1");
    
    // 分析因子
    println!("\n因子分解:");
    for &d in &d_values {
        let factors = factorize(d as u32);
        println!("  D={}: {}", d, factors);
    }

    // 检查是否有公共结构
    println!("\n检查 D 与粒子代数:");
    println!("  D=2: 2 = 2¹ → 光子? (自旋1)");
    println!("  D=3: 3 = 3¹ → 轻子(第2代)? (3个颜色?)");
    println!("  D=6: 6 = 2×3 → 强子? (U(1)×SU(3)?)");
    println!("  D=7: 7 = 素数 → 轻子(第3代)? (无明显结构)");

    // ========================================================================
    // 阶段 5: 穷尽搜索不同的 D-粒子映射
    // ========================================================================

    println!("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
    println!("阶段 5: 穷尽搜索 - 是否存在更好的 D 映射?");
    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n");

    // 对于五常数多项式，检查是否其他 D 组合也能给出五个常数
    let constants = [
        ("α⁻¹", 137.036),
        ("mμ/me", 206.768),
        ("mp/me", 1836.15),
        ("mn/me", 1838.68),
        ("mτ/me", 3477.23),
    ];

    println!("测试: P(D) 在哪些 D 处接近物理常数 (误差 < 1%)\n");
    
    for d in 1..=15i128 {
        let p_d = five_const_poly(d);
        let mut matches = Vec::new();
        
        for (name, value) in &constants {
            let error = ((p_d as f64 - value) / value * 100.0).abs();
            if error < 1.0 {
                matches.push(format!("{} ({:.3}%)", name, error));
            }
        }
        
        if !matches.is_empty() {
            println!("  D={:2}: P(D) = {:5} → {}", d, p_d, matches.join(", "));
        }
    }

    // ========================================================================
    // 阶段 6: E7 多项式的 D-粒子映射
    // ========================================================================

    println!("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
    println!("阶段 6: E7 多项式 D-粒子映射");
    println!("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n");

    // E7 多项式: P(D) = D⁴ - 2D³ + 2D + 1
    let e7_poly = |d: i128| -> i128 {
        d.pow(4) - 2*d.pow(3) + 2*d + 1
    };

    println!("E7 多项式: P(D) = D⁴ - 2D³ + 2D + 1\n");
    println!("  D | P(D) | 最近常数");
    println!("  --|------|------------------");
    
    for d in 1..=10i128 {
        let p_d = e7_poly(d);
        let nearest = find_nearest(&constants, p_d as f64);
        println!("  {:2} | {:5} | {}", d, p_d, nearest);
    }

    println!("\n关键观察:");
    println!("  P(4) = 137 → α⁻¹ (D=4 是时空维度)");
    println!("  P(1) = 2, P(2) = 5 → 小素数，可能是 Fibonacci 相关");
    println!("  P(3) = 34 = 2×17 = Fibonacci F9");

    // ========================================================================
    // 综合结论
    // ========================================================================

    println!("\n================================================================================");
    println!("                         D-粒子映射综合结论");
    println!("================================================================================");

    println!("\n[发现]");
    println!("1. 五常数多项式的 D 映射:");
    println!("   - D=2 → α⁻¹ (无明显物理理由)");
    println!("   - D=3 → mμ/me (第二代轻子)");
    println!("   - D=6=2×3 → 核子 (可能是 U(1)×SU(3) 结构?)");
    println!("   - D=7 → mτ/me (第三代轻子)");

    println!("\n2. E7 多项式的 D 映射:");
    println!("   - D=4 → α⁻¹ (时空维度，有物理意义)");
    println!("   - 其他 D 无物理常数匹配");

    println!("\n[仍然缺失的物理机制]");
    println!("- 为什么五常数多项式中 D=2 对应 α⁻¹ 而不是 D=4?");
    println!("- 为什么 D 值与粒子代数(1,2,3代)有模糊对应?");
    println!("- 是否存在统一的选择原理连接 D 与粒子性质?");

    println!("\n[建议的下一步]");
    println!("- 从表示论角度分析: D 可能与某个对称群的表示维数有关");
    println!("- 从规范理论角度: D 可能与规范群的 Casimir 不变量有关");
    println!("- 从弦理论角度: D 可能与紧致化维数有关");

    println!("\n================================================================================");
    println!("          完成 - D-粒子映射探索");
    println!("================================================================================");
}

fn factorize(mut n: u32) -> String {
    if n == 1 { return "1".to_string(); }
    let mut factors = Vec::new();
    let mut d = 2u32;
    while d * d <= n {
        while n % d == 0 {
            factors.push(d);
            n /= d;
        }
        d += 1;
    }
    if n > 1 { factors.push(n); }
    if factors.len() == 1 {
        format!("{} (素数)", factors[0])
    } else {
        factors.iter().map(|f| f.to_string()).collect::<Vec<_>>().join(" × ")
    }
}

fn find_nearest(constants: &[(&str, f64)], value: f64) -> String {
    let mut min_error = f64::MAX;
    let mut nearest = "";
    
    for (name, c_value) in constants {
        let error = ((value - c_value) / c_value * 100.0).abs();
        if error < min_error && error < 1.0 {
            min_error = error;
            nearest = name;
        }
    }
    
    if nearest.is_empty() {
        "---".to_string()
    } else {
        format!("{} ({:.3}%)", nearest, min_error)
    }
}
