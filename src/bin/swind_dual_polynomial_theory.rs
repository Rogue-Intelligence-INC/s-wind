/// 计算多项式在 D 处的值
fn eval_poly(coeffs: &[i64], d: u32) -> i64 {
    let d = d as i64;
    coeffs[0] * d.pow(4) + coeffs[1] * d.pow(3) + coeffs[2] * d.pow(2) + coeffs[3] * d + coeffs[4]
}
