    println!("───────────────────────────────────────────────────────────────────────");
    
    let alpha_inv = 137i128;
    let alpha_inv_sq = alpha_inv * alpha_inv;
    let q_neg6 = eval_q(&q_coeffs, -6);
    
    println!("  α⁻¹ = {}", alpha_inv);
    println!("  α⁻² = {} × {} = {}", alpha_inv, alpha_inv, alpha_inv_sq);
    println!("  Q(-6) = {}", q_neg6);
    println!("  93 × Q(-6) = 93 × {} = {}", q_neg6, 93 * q_neg6);
    println!("  α⁻² + 93×Q(-6) = {} + {} = {}", alpha_inv_sq, 93 * q_neg6, alpha_inv_sq + 93 * q_neg6);
    println!("  mZ/me (CODATA) ≈ 178450");
