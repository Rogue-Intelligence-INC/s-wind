fn eval_p(coeffs: &[i128; 5], d: i128) -> i128 {
    coeffs[0] * d.pow(4) + coeffs[1] * d.pow(3) + 
    coeffs[2] * d.pow(2) + coeffs[3] * d + coeffs[4]
}

fn eval_q(coeffs: &[i128; 5], d: i128) -> i128 {
    coeffs[0] * d.pow(4) + coeffs[1] * d.pow(3) + 
    coeffs[2] * d.pow(2) + coeffs[3] * d + coeffs[4]
}

fn eval_i(d: i128) -> i128 {
    -d.pow(3) + 4 * d.pow(2) + 11 * d + 97
}

fn gcd(a: i128, b: i128) -> i128 {
    if b == 0 { a.abs() } else { gcd(b, a % b) }
}

fn is_prime(n: i128) -> bool {
    if n < 2 { return false; }
    if n == 2 { return true; }
    if n % 2 == 0 { return false; }
    let sqrt_n = isqrt(n) + 1;
    for i in (3..=sqrt_n).step_by(2) {
        if n % i == 0 { return false; }
    }
    true
}

fn isqrt(n: i128) -> i128 {
    if n < 0 { return 0; }
    let mut x = n;
    let mut y = (x + 1) / 2;
    while y < x {
        x = y;
        y = (x + n / x) / 2;
    }
    x
}

fn icbrt(n: i128) -> i128 {
    if n <= 0 { return 0; }
    let mut x = (n as f64).cbrt().round() as i128;
    // 精确验证
    while x > 0 && x * x * x > n { x -= 1; }
    while (x + 1) * (x + 1) * (x + 1) <= n { x += 1; }
    x
}
