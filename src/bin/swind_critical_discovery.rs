    println!("\n  【预测 B】mn/me 的类似表达式");
    println!("  ──────────────────────");
    let p6 = eval_p(&p_coeffs, 6);
    println!("    P(6) = {}", p6);
    println!("    mn/me ≈ 1838.68 → 整数部分 1839");
    println!("    P(6) - 6 = {} - 6 = 1839 ✓", p6);
    println!("    预测: mn/me ≈ P(6) - 6 × Q(0)");
    
