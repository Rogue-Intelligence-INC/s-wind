    println!("\n\n═══════════════════════════════════════════════════════════════════════");
    println!("  ★ 最核心的可证伪预测 ★");
    println!("═══════════════════════════════════════════════════════════════════════\n");
    
    println!("  1. 质子质量比公式:");
